#  Сеть задана IP-адресом 192.168.32.160
#  и маской сети 255.255.255.240.
#  Сколько в этой сети IP-адресов, для которых сумма единиц в двоичной записи IP-адреса чётна?

import ipaddress
net = ipaddress.ip_network('192.168.32.160/255.255.255.240',0)

counter = 0
for ip in net: # 192.168.32.160.__str__() -> '192.168.32.160'.split('.') -> ['192', '168', '32', '160']
    if "".join([bin(int(i))[2:] for i in ip.__str__().split('.')]).count("1") % 2 == 0:
        counter += 1
print(counter)
