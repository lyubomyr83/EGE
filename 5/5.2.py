"""
Алгоритм получает на вход натуральное число N и строит по нему новое число R следующим образом:

1.  Строится двоичная запись числа N.
2.  В конец двоичной записи добавляется двоичный код остатка от деления числа N на 4.
3.  Результатом работы алгоритма становится десятичная запись полученного числа R.

Назовём доступными числа, которые могут получиться в результате работы этого алгоритма.
Например, числа 27 и 58  — доступные.
Определите количество доступных чисел, принадлежащих отрезку [1 000 000 000; 1 789 456 123]

Ответ: 296046047
"""


def count_Ns(L, U, mod_value, multiplier):
    # 1. Находим ПЕРВОЕ N, которое дает R >= L
    # Начинаем поиск с примерного значения (L // multiplier)
    n_start = L // multiplier
    while n_start * multiplier + mod_value < L:
        n_start += 1

    # 2. Подгоняем n_start под нужный остаток
    while n_start % 4 != mod_value:
        n_start += 1

    # 3. Находим ПОСЛЕДНЕЕ N, которое дает R <= U
    n_end = U // multiplier
    while n_end * multiplier + mod_value > U:
        n_end -= 1

    # 4. Подгоняем n_end под нужный остаток
    while n_end % 4 != mod_value:
        n_end -= 1

    # 5. Если диапазон корректен, считаем количество чисел с шагом 4
    if n_start > n_end:
        return 0
    return (n_end - n_start) // 4 + 1


L, U = 1_000_000_000, 1_789_456_123

res = 0
res += count_Ns(L, U, 0, 2)  # Остаток 0: R = 2N + 0
res += count_Ns(L, U, 1, 2)  # Остаток 1: R = 2N + 1
res += count_Ns(L, U, 2, 4)  # Остаток 2: R = 4N + 2
res += count_Ns(L, U, 3, 4)  # Остаток 3: R = 4N + 3

print(res)
