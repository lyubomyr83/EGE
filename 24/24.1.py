"""
Текстовый файл состоит не более чем из 106 символов X, Y и Z.
Определите максимальное количество идущих подряд символов,
среди которых каждые два соседних различны.
"""

data = open("24.1.txt").readline()

# 1 решение с помощью регулярных выражений
from re import finditer

# Паттерн:
# (?: ... )*  -- повторяем группу без захвата
# (.)         -- берем любой символ (группа 1)
# (?!\1)      -- смотрим вперед: следующий символ НЕ должен быть таким же, как в группе 1
# .           -- берем последний символ в цепочке (перед которым проверка уже не нужна)

# Используем finditer, чтобы забирать всё найденное совпадение целиком (group(0))
matches = finditer(r'(?:(.)(?!\1))*.', data)
ans = max(len(m.group(0)) for m in matches)

print(ans)

# 2 решение с помощью цикла
max_counter = 0
counter = 1

for i in range(len(data) - 1):  #'XXYZYZX'  7
    if data[i] != data[i + 1]:
        counter += 1
    else:
        if counter > max_counter:
            max_counter = counter
        counter = 1
print(max_counter)
