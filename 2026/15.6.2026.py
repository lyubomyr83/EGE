"""
Обозначим через ДЕЛ(n, m) утверждение «натуральное число n делится без остатка на
натуральное число m». Задан отрезок B = [30; 40]. Определите минимальное количество
элементов множества A при котором формула
(x ∈ A) ∨ (ДЕЛ(x, 12) → (x not ∈ B))
тождественно истинна (т.е. принимает значение 1) при любом целом положительном значении переменной x?
"""

A = [] # Сюда соберем все x, которые ОБЯЗАНЫ быть в A
B = list(range(30, 41))

for x in range(1001):
    # Нам нужно, чтобы выражение было истинным (1) всегда.
    # Проверим, при каких x выражение становится ЛОЖНЫМ, если x НЕ в A.
    # Если (x in A) = False делает всё выражение ложным, значит x ДОЛЖЕН быть в A.
    if not((x in A) or ((x % 12 == 0) <= (x not in B))):
        A.append(x)

print(len(A))