"""
Сеть задана IP-адресом одного из входящих в неё узлов 188.163.128.179
и сетевой маской 255.255.240.0.
Определите наименьший IP-адрес данной сети, который может быть присвоен компьютеру.
В ответе укажите сумму октетов у найденного IP-адреса.

"""

from ipaddress import ip_network

net = ip_network('188.163.128.179/255.255.240.0', strict=0)
print(net[0])
print(sum(map(int, str(net[1]).split('.'))))
