"""
В файле содержится последовательность целых чисел. Определите количество пар идущих
подряд элементов, в которых элементы не равны друг другу, а абсолютная разность между
ними кратна минимальному положительному элементу последовательности, который кратен
9. В ответе запишите два числа: сначала количество найденных пар, затем максимальную
сумму элементов таких пар.
"""

numbers = [int(i) for i in open('17-1.txt').readlines()]
_more_zero = min([i for i in numbers if i > 0 and i % 9 == 0])

all_pairs = []

for i in range(len(numbers)-1):
    n1 = numbers[i]
    n2 = numbers[i+1]

    if n1 != n2 and (abs(n1 - n2) % _more_zero == 0):
        all_pairs.append(n1 + n2)


print(len(all_pairs), max(all_pairs))
