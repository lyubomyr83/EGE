"""
В файле содержится последовательность целых чисел от -10 000 до 10 000. Определите количество пар идущих подряд элементов, в которых хотя бы одно число отрицательное, а их
сумма больше количества чисел в файле, которые делятся на 27 без остатка. В ответе запишите два числа: сначала количество найденных пар, затем максимальную сумму элементов
таких пар.
"""

f = [int(i) for i in open('17-3.txt').readlines()]

_27 = len([i for i in f if i % 27 == 0]) # количества чисел в файле, которые делятся на 27 без остатка

all_pairs = []

for i in range(len(f) - 1):
    n1 = f[i]
    n2 = f[i + 1]
    if n1 < 0 or n2 < 0:
        if  n1 + n2 > _27:
            all_pairs.append(n1 + n2)

print(len(all_pairs), max(all_pairs))
