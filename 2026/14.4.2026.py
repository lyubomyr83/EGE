"""
Значение арифметического выражения
5 · 7776**2013 + 4 · 1296**2015 − 3 · 216**2017 + 2 · 36**2017 − 6**2019 + 2023
записали в 36-ричной системе счисления. Определите количество цифр, не превышающих
9 в этой записи.


"""

answer = 5 * 7776**2013 + 4 * 1296**2015 - 3 * 216**2017 + 2 * 36**2017 - 6**2019 + 2023

s = 0

while answer > 0:
    if (answer % 36) < 10:
        s += 1

    answer = answer // 36

print(s)