"""
В файле содержится последовательность целых чисел. Определите количество пар идущих
подряд элементов, у которых сумма элементов меньше минимального числа из последовательности,
которое положительно и кратно 7. В ответе запишите два числа: сначала количество найденных пар, затем абсолютное значение максимальной суммы.
"""

f = [int(i) for i in open('17-6.txt').readlines()]

all_pairs = []

min_f = min([i for i in f if i > 0 and i % 7 == 0])

for i in range(len(f) - 1):
    num1 = f[i]
    num2 = f[i + 1]

    if (num1 + num2) < min_f:
        all_pairs.append(num1 + num2)

print(len(all_pairs), abs(max(all_pairs)))
