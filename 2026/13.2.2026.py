"""
Узел имеет IP-адрес 210.185.140.126.
Маска сети равна 255.255.255.252.
Определите наименьший возможный IP-адрес в этой сети (адрес сети) и в ответе запишите сумму значений
его октетов.

"""

from ipaddress import ip_network

net = ip_network('210.185.140.126/255.255.255.252', strict=0)
print(net[0])
print(sum(map(int, str(net[0]).split('.'))))