"""
В файле содержится последовательность целых чисел от 1 до 100 000. Определите количество пар идущих подряд элементов, у которых сумма остатков от деления на 20 равна
минимальному числу в файле. В ответе запишите два числа: сначала количество найденных
пар, затем максимальную сумму элементов таких пар.
"""

f = [int(i) for i in open("17-1.txt").readlines()]

all_pairs = []

min_f = min(f)

for i in range(len(f) - 1):
    num1 = f[i]
    num2 = f[i + 1]

    if (num1 % 20) + (num2 % 20) == min_f:
        all_pairs.append(num1 + num2)

print(len(all_pairs), max(all_pairs))
