"""
В файле содержится последовательность целых чисел. Определите количество пар идущих
подряд элементов, в которых остаток от деления хотя бы одного элемента пары на 33 равен
минимальному числу в последовательности. В ответе запишите два числа: сначала количество найденных пар,
затем максимальную сумму элементов таких пар
"""

f = [int(i) for i in open('17-2.txt').readlines()]

min_num = min(f)

all_pairs = []

for i in range(len(f) - 1):
    num1 = f[i]
    num2 = f[i + 1]

    if (num1 % 33 == min_num) or (num2 % 33 == min_num):
        all_pairs.append(num1 + num2)

print(len(all_pairs), max(all_pairs))
